package packet;

public class RotaAdimi {
    public String from;
    public String to;
    public double mesafe;
    public int sure;
    public double ucret;
    public String aracTuru;

    public RotaAdimi(String from, String to, double mesafe, int sure, double ucret, String aracTuru) {
        this.from = from;
        this.to = to;
        this.mesafe = mesafe;
        this.sure = sure;
        this.ucret = ucret;
        this.aracTuru = aracTuru;
    }
}